# 工具兼容函数（供其他模块 import）
# ═══════════════════════════════════════════════════════════════

def _strip_code_fence_compat(text: str) -> str:
    """统一的代码围栏剥离函数"""
    text = text.strip()
    if text.startswith("```json"):
        text = text[7:]
    elif text.startswith("```"):
        text = text[3:]
    if text.endswith("```"):
        text = text[:-3]
    return text.strip()
